-- One-time setup for a new, empty PostgreSQL database (such as Render Postgres).
-- Run this single file in pgAdmin's Query Tool. It does not delete existing data.
-- Do not run the numbered migrations after this file: it already creates the final schema.

BEGIN;

CREATE TABLE IF NOT EXISTS public.cars (
  car_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name varchar(120) NOT NULL,
  capacity integer NOT NULL CHECK (capacity BETWEEN 1 AND 99),
  starting_rate numeric(12, 2) NOT NULL CHECK (starting_rate >= 0),
  category varchar(80) NOT NULL DEFAULT 'Car',
  transmission varchar(40) NOT NULL DEFAULT 'Automatic',
  status varchar(20) NOT NULL DEFAULT 'available'
    CHECK (status IN ('available', 'rented', 'maintenance', 'unavailable')),
  image_url text,
  description text,
  is_featured boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.booking_statuses (
  booking_status_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(20) NOT NULL UNIQUE,
  label varchar(40) NOT NULL
);

INSERT INTO public.booking_statuses (code, label)
VALUES
  ('pending', 'Pending review'),
  ('confirmed', 'Confirmed'),
  ('completed', 'Completed'),
  ('cancelled', 'Cancelled')
ON CONFLICT (code) DO UPDATE SET label = EXCLUDED.label;

CREATE TABLE IF NOT EXISTS public.booking_details (
  booking_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  car_id bigint NOT NULL REFERENCES public.cars(car_id) ON DELETE RESTRICT,
  booking_status_id integer NOT NULL REFERENCES public.booking_statuses(booking_status_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  customer_name varchar(120),
  customer_phone varchar(40) NOT NULL,
  customer_email varchar(254) NOT NULL,
  pickup_date date NOT NULL,
  return_date date NOT NULL,
  pickup_time time NOT NULL,
  return_time time NOT NULL,
  pickup_location varchar(250) NOT NULL,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT booking_details_date_order CHECK (return_date >= pickup_date),
  CONSTRAINT booking_details_notes_length CHECK (notes IS NULL OR char_length(notes) <= 2000)
);

CREATE INDEX IF NOT EXISTS booking_details_status_created_at_idx
  ON public.booking_details (booking_status_id, created_at DESC);
CREATE INDEX IF NOT EXISTS booking_details_car_dates_idx
  ON public.booking_details (car_id, pickup_date, return_date);

CREATE TABLE IF NOT EXISTS public.customer_moments (
  customer_moment_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  customer_name varchar(120) NOT NULL,
  occasion varchar(160),
  image_url text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS customer_moments_created_at_idx
  ON public.customer_moments (created_at DESC);

COMMIT;
