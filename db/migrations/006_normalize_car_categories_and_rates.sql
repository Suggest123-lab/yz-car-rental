-- Run after 005_add_booking_preferences.sql.
-- Replaces the legacy category text and starting rate with normalized categories and trip-specific rates.

BEGIN;

CREATE TABLE IF NOT EXISTS public.car_categories (
  category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(80) NOT NULL UNIQUE
);

INSERT INTO public.car_categories (name)
VALUES ('Hatchback'), ('Sedan'), ('MPV'), ('SUV'), ('PICKUP')
ON CONFLICT (name) DO NOTHING;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'cars' AND column_name = 'starting_rate'
  ) AND NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'cars' AND column_name = 'city_rate'
  ) THEN
    ALTER TABLE public.cars RENAME COLUMN starting_rate TO city_rate;
  END IF;
END $$;

ALTER TABLE public.cars
  ADD COLUMN IF NOT EXISTS outside_cdo_rate numeric(12, 2) NOT NULL DEFAULT 0 CHECK (outside_cdo_rate >= 0),
  ADD COLUMN IF NOT EXISTS outside_region_rate numeric(12, 2) NOT NULL DEFAULT 0 CHECK (outside_region_rate >= 0),
  ADD COLUMN IF NOT EXISTS carwash_rate numeric(12, 2) NOT NULL DEFAULT 0 CHECK (carwash_rate >= 0),
  ADD COLUMN IF NOT EXISTS category_id integer;

UPDATE public.cars AS car
SET category_id = category.category_id
FROM public.car_categories AS category
WHERE lower(category.name) = lower(car.category);

UPDATE public.cars
SET category_id = (SELECT category_id FROM public.car_categories WHERE name = 'Sedan')
WHERE category_id IS NULL;

ALTER TABLE public.cars
  ALTER COLUMN category_id SET NOT NULL,
  ADD CONSTRAINT cars_category_id_fkey
    FOREIGN KEY (category_id) REFERENCES public.car_categories(category_id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  DROP COLUMN category;

COMMIT;
