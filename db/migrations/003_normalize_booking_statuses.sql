-- Replaces the status code relationship with an integer primary-key relationship.
-- Run after 002_create_booking_tables.sql.

BEGIN;

ALTER TABLE public.booking_statuses
  ADD COLUMN IF NOT EXISTS booking_status_id integer GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE public.booking_statuses
  ALTER COLUMN booking_status_id SET NOT NULL;

ALTER TABLE public.booking_details
  ADD COLUMN IF NOT EXISTS booking_status_id integer;

UPDATE public.booking_details AS booking
SET booking_status_id = status.booking_status_id
FROM public.booking_statuses AS status
WHERE booking.status_code = status.code
  AND booking.booking_status_id IS NULL;

ALTER TABLE public.booking_details
  ALTER COLUMN booking_status_id SET NOT NULL;

ALTER TABLE public.booking_details
  DROP CONSTRAINT IF EXISTS booking_details_status_code_fkey,
  DROP COLUMN IF EXISTS status_code;

ALTER TABLE public.booking_statuses
  DROP CONSTRAINT IF EXISTS booking_statuses_pkey,
  DROP COLUMN IF EXISTS sort_order,
  DROP COLUMN IF EXISTS is_final;

ALTER TABLE public.booking_statuses
  ADD CONSTRAINT booking_statuses_pkey PRIMARY KEY (booking_status_id);

ALTER TABLE public.booking_statuses
  ADD CONSTRAINT booking_statuses_code_key UNIQUE (code);

ALTER TABLE public.booking_details
  ADD CONSTRAINT booking_details_booking_status_id_fkey
  FOREIGN KEY (booking_status_id)
  REFERENCES public.booking_statuses(booking_status_id)
  ON UPDATE CASCADE ON DELETE RESTRICT;

DROP INDEX IF EXISTS public.booking_details_status_created_at_idx;
CREATE INDEX booking_details_status_created_at_idx
  ON public.booking_details (booking_status_id, created_at DESC);

COMMIT;
